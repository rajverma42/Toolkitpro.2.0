export function t(key: string, lang: "en" | "hi" = "en"): string {
  const dict = I18N[lang] || I18N.en;
  if (dict && Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
  return (I18N.en && Object.prototype.hasOwnProperty.call(I18N.en, key)) ? I18N.en[key] : key;
}

export function getToolName(tool: { id: string; name: string }, lang: "en" | "hi" = "en"): string {
  if (lang === "hi" && TOOL_TR[tool.id]?.name) return TOOL_TR[tool.id].name!;
  return tool.name;
}

